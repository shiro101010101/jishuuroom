export function getExamPage(slug: string): ExamPage | null {
  const exam = EXAMS.find(e => e.slug === slug)
  if (!exam) return null
  const spec = SPECS[exam.slug]
  return { slug: exam.slug, emoji: exam.emoji, ...spec, faq: [...spec.faq, ...COMMON_FAQ] }
}

export const EXAM_PAGE_SLUGS: ExamSlug[] = EXAMS.map(e => e.slug)
